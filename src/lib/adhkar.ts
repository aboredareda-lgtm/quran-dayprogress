export function getAdhkar(period: AdhkarPeriod): readonly Dhikr[] {
  return ADHKAR.filter((dhikr) => !dhikr.periods || dhikr.periods.includes(period)).map((dhikr) => ({
    ...dhikr,
    title: period === "evening" ? dhikr.eveningTitle ?? dhikr.title : dhikr.title,
    text: period === "evening" ? dhikr.eveningText ?? dhikr.text : dhikr.text,
  }));
}

export function incrementDhikr(count: number, repetitions: number) {
  return Math.min(repetitions, Math.max(0, count) + 1);
}